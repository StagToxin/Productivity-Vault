export type TKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];
export const dicts: Record<Lang, Dict> = { tr, en };

export function makeT(lang: Lang) {
  const d = dicts[lang] ?? tr;
  const t = (key: TKey, vars?: Record<string, string | number>) => {
    let s = (d[key] as string) ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
  return Object.assign(t, { dow: d.dow, months: d.months, lang });
}
export type T = ReturnType<typeof makeT>;
